'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const page=fs.readFileSync(path.join(__dirname,'..','public/mongo-admin-console.html'),'utf8');
const engine=fs.readFileSync(path.join(__dirname,'..','database/elections.js'),'utf8');
assert.match(page,/id="setupStep1"/);
assert.match(page,/id="setupStep2"/);
assert.match(page,/id="setupStep3"/);
assert.match(page,/id="setupStep4"/);
assert.match(page,/id="wizardAddPosition"/);
assert.match(page,/id="wizardCandidates"/);
assert.match(page,/id="wizardReview"/);
assert.match(page,/readWizardPositions\(\)/);
assert.match(page,/readWizardCandidates\(\)/);
assert.match(page,/maxVotes:pos\.maxVotes|title,maxVotes,candidates/);
assert.match(page,/photoToDataUri/);
assert.match(page,/showWizardStep\(Math\.min\(4,wizardStep\+1\)\)/);
assert.match(page,/id="candidatePosition"/);
assert.match(page,/new Set\(data\.candidates\.map\(c=>c\.position\)\)/);
assert.doesNotMatch(page,/id="kagawad"/i);
assert.doesNotMatch(page,/id="kapitan"/i);
assert.doesNotMatch(engine,/name\.toLowerCase\(\)==='kagawad'/);
assert.doesNotMatch(engine,/name\.toLowerCase\(\)==='kapitan'/);
console.log('PASS: Four-step dynamic election wizard, arbitrary positions and configurable vote maxima');
