'use strict';
const assert=require('node:assert/strict');
const packageFile=require('../package.json');
assert.equal(packageFile.scripts.start,'node mongo-auth-preview.js');
assert.equal(packageFile.scripts['start:legacy-mysql'],'node server.js');
assert.equal(packageFile.main,'mongo-auth-preview.js');
const fs=require('node:fs'),path=require('node:path');
const server=fs.readFileSync(path.join(__dirname,'..','mongo-auth-preview.js'),'utf8');
assert.ok(server.includes("process.env.ENABLE_MONGODB_VOTE_TEST==='true'"),'Vote test gate missing');
assert.ok(server.includes("!/(?:")||server.includes("!/_(")||server.includes("!/_"),'Test database suffix guard missing');
assert.ok(server.includes("process.env.MONGODB_DB_NAME"),'Voting must validate the configured database name');
console.log('PASS: Production default starts MongoDB and MySQL remains legacy-only');
