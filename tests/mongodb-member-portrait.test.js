'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto'),fs=require('node:fs'),path=require('node:path');
const {decodePhoto,encryptPortrait,decryptPortrait}=require('../database/member-portrait');
const key=crypto.randomBytes(32);
const jpg=Buffer.concat([Buffer.from([255,216,255,224]),crypto.randomBytes(180)]);
const photo='data:image/jpeg;base64,'+jpg.toString('base64');
assert.equal(decodePhoto(photo).mime,'jpeg');
const encrypted=encryptPortrait(photo,key);
assert.ok(encrypted.startsWith('portrait:v1:jpeg:'));
assert.ok(!encrypted.includes(jpg.toString('base64')));
assert.equal(decryptPortrait(encrypted,key),photo);
assert.throws(()=>decryptPortrait(encrypted,crypto.randomBytes(32)));
assert.throws(()=>decodePhoto('data:image/svg+xml;base64,abcd'),TypeError);
assert.throws(()=>decodePhoto('data:image/png;base64,'+jpg.toString('base64')),TypeError);
assert.throws(()=>decodePhoto('data:image/jpeg;base64,'+Buffer.alloc(150001).toString('base64')),TypeError);
const root=path.join(__dirname,'..');
const server=fs.readFileSync(path.join(root,'mongo-auth-preview.js'),'utf8');
const register=fs.readFileSync(path.join(root,'public/mongo-enrollment-preview.html'),'utf8');
const member=fs.readFileSync(path.join(root,'public/mongo-member-preview.html'),'utf8');
const enrolled=fs.readFileSync(path.join(root,'database/member-enrollment.js'),'utf8');
assert.match(register,/profilePhoto:capturePortrait\(\)/);
assert.match(enrolled,/portraitEncrypted:portrait/);
assert.match(server,/app\.get\('\/api\/member\/profile'/);
assert.match(server,/if\(!auth\|\|auth\.role!=='member'\)/);
assert.match(server,/decryptPortrait\(member\.portraitEncrypted,keyFromEnv\(\)\)/);
assert.match(member,/await request\('\/api\/member\/profile'\)/);
console.log('PASS: consented enrollment portraits encrypted at rest, tamper rejected and member-scoped');
